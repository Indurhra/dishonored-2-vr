"""Regenerate src/Src/SeedsData.inc from learned DVR_grips.txt / DVR_hands.txt.

The mod learns how each hand holds each weapon while you play (GpuTrace: WeaponGrip, HandQ) and keeps it in those two
files in the game folder. A fresh install has neither, so the first moments with each weapon would look wrong until it
is learned again. These "seeds" ship the developer's learned files inside the DLL; Seeds::Install writes them out only
when the player has none of their own. Run after a session that learned good grips for every weapon you care about:

    python tools/make_seeds.py "C:/Program Files (x86)/Steam/steamapps/common/Dishonored2"
"""
import os
import sys

game = sys.argv[1] if len(sys.argv) > 1 else r"C:\Program Files (x86)\Steam\steamapps\common\Dishonored2"
out = os.path.join(os.path.dirname(__file__), "..", "src", "Src", "SeedsData.inc")
PIECE = 8000   # MSVC: a single string literal piece must stay under 16 KB


def literal(name, path):
    text = open(path, "r", encoding="ascii").read().replace("\r\n", "\n")
    lines = [f"// {os.path.basename(path)}: {text.count(chr(10))} lines"]
    lines.append(f"static const char {name}[] =")
    for i in range(0, len(text), PIECE):
        chunk = text[i:i + PIECE].replace("\\", "\\\\").replace("\"", "\\\"").replace("\n", "\\n")
        lines.append(f'    "{chunk}"')
    lines[-1] += ";"
    return "\n".join(lines) + "\n"


with open(out, "w", encoding="ascii", newline="\r\n") as f:
    f.write("// Generated by tools/make_seeds.py -- do not edit by hand.\n")
    f.write(literal("kGripsSeed", os.path.join(game, "DVR_grips.txt")))
    f.write(literal("kHandsSeed", os.path.join(game, "DVR_hands.txt")))
print("wrote", os.path.abspath(out))
